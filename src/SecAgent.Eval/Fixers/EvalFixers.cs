// The eval fixers follow the pipeline fixers (src/SecAgent.Agents/Fixers/Fixers.cs) step by step: same context components, prompts and
// schemas, and the same edit functions (FixEdits). What differs is the plumbing the pipeline gets from AgentServices (SQL store, tool
// allow-list, git worktrees, GitHub): here the workspace is a local git repo and tools are plain calls. See docs/evaluation.md.

/// <summary>Lowest safe version lookup. The pipeline asks nuget.org (nuget.resolve tool); the harness stays offline and deterministic.</summary>
public interface IPackageVersionResolver
{
    (string? LowestSafe, string? Latest) Resolve(GoldenCase c, string package, string minVersion);
}

/// <summary>Versions come from the case (package_versions) or default to the finding's fixed version.</summary>
public sealed class OfflinePackageVersionResolver : IPackageVersionResolver
{
    public (string? LowestSafe, string? Latest) Resolve(GoldenCase c, string package, string minVersion)
    {
        var known = c.PackageVersions.TryGetValue(package, out var v) && v.Count > 0 ? v : [minVersion];
        var ordered = known.OrderBy(x => x, Comparer<string>.Create(Verification.Versions.Compare)).ToList();
        return (ordered.FirstOrDefault(x => Verification.Versions.Compare(x, minVersion) >= 0), ordered.LastOrDefault());
    }
}

/// <summary>Mirrors LibraryFixer: bump the PackageReference to the lowest safe version; the model assesses upgrade risk for the reviewer.</summary>
public sealed class LibraryEvalFixer(IModelStep step, IPackageVersionResolver resolver) : IEvalFixer
{
    public string Id => "library";

    public async Task<FixResult> ApplyAsync(CaseContext ctx, CancellationToken ct)
    {
        var f = ctx.Finding; var root = ctx.Workspace.Root;
        var pkg = FixEdits.PackageName(f);
        var minSafe = FixEdits.MinimumSafeVersion([f]);
        var (lowest, latest) = resolver.Resolve(ctx.Case, pkg, minSafe);
        var target = lowest ?? minSafe;
        var csproj = FixEdits.FindManifest(root, pkg);
        var rel = Path.GetRelativePath(root, csproj);
        var text = await File.ReadAllTextAsync(csproj, ct);
        var line = FixEdits.ManifestLine(text, pkg);
        var lockRel = Path.Combine(Path.GetDirectoryName(rel)!, "packages.lock.json");
        var call = await step.RunAsync(ctx, "fix", "library", "fix", "fix-library-output", f.SeverityEffective ?? f.SeverityScanner,
        [
            new("finding", $"finding:{f.FindingId}", JsonSerializer.Serialize(new[] { JsonDocument.Parse(LlmStep.FindingJson(f)).RootElement }, Schema.JsonIndented)),
            new("tool_output", $"manifest:{rel}", $"Manifest: {rel}\n{line}\nResolver: lowest safe stable version of {pkg} >= {minSafe} is {target} (latest {latest}).\nLock file: {lockRel} (regenerated by dotnet restore)."),
            new("run_summary", $"run:{ctx.PackRunId}", $"PR #{f.PrNumber} {f.Repo}"),
        ], ct);
        await File.WriteAllTextAsync(csproj, FixEdits.BumpPackageVersion(text, pkg, target), ct);
        return new FixResult(true, false, $"Bump {pkg} {f.ComponentVersion} → {target}", Notes: new()
        {
            ["package"] = pkg, ["from"] = f.ComponentVersion ?? "", ["to"] = target, ["manifest"] = rel,
            ["risk"] = Str(call.Json, "breaking_change_risk"), ["reviewer_note"] = Str(call.Json, "reviewer_note"),
        });
    }

    internal static string Str(JsonElement e, string p) => e.TryGetProperty(p, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString()! : "";
}

/// <summary>Mirrors SecretsFixer: locate the literal by HMAC in a JSON config file, replace it with a Key Vault reference, raise a rotation task.</summary>
public sealed class SecretsEvalFixer(ConfigSnapshot cfg, IModelStep step, SecretMasker masker) : IEvalFixer
{
    public string Id => "secrets";

    public async Task<FixResult> ApplyAsync(CaseContext ctx, CancellationToken ct)
    {
        var f = ctx.Finding;
        var path = Path.Combine(ctx.Workspace.Root, f.FilePath!);
        var text = await File.ReadAllTextAsync(path, ct);
        var located = path.EndsWith(".json") ? FixEdits.LocateJsonSecret(text, f.SecretHash) : null;
        if (located is not var (configPath, literal)) throw new InvalidOperationException("could not locate the secret literal by HMAC");
        masker.Register(literal);
        var rp = cfg.RulePacks["secret"];
        var call = await step.RunAsync(ctx, "fix", "secrets", "fix", "fix-secrets-output", f.SeverityEffective ?? f.SeverityScanner,
        [
            new("finding", $"finding:{f.FindingId}", LlmStep.FindingJson(f) + $"\nconfig_path: {configPath}"),
            new("code_snippet", f.CodeSnippetRef ?? $"file:{f.FilePath}", masker.Mask(text)),
            new("rule_pack", $"rule-packs/secret@{rp.Version}", rp.Guidance),
        ], ct);
        var name = FixEdits.KeyVaultSecretName(LibraryEvalFixer.Str(call.Json, "secret_name"), configPath);
        var reference = FixEdits.KeyVaultReference(SecretsFixer.VaultName, name);
        await File.WriteAllTextAsync(path, FixEdits.ReplaceSecretLiteral(text, literal, reference), ct);
        lock (ctx) ctx.HumanTasks.Add("rotation");
        return new FixResult(true, false, $"Key Vault reference for {configPath}; rotation task raised", Notes: new()
        {
            ["config_path"] = configPath, ["secret_name"] = name, ["reference"] = reference,
            ["rotation_note"] = LibraryEvalFixer.Str(call.Json, "rotation_note"), ["reviewer_note"] = LibraryEvalFixer.Str(call.Json, "reviewer_note"),
        });
    }
}

/// <summary>Mirrors UnsafeCodeFixer: the model rewrites the enclosing method and writes one xUnit test; one repair call when the output uses a
/// type from another database provider (rules-as-code pre-build check).</summary>
public sealed class UnsafeCodeEvalFixer(ConfigSnapshot cfg, IModelStep step) : IEvalFixer
{
    public string Id => "unsafe_code";

    public async Task<FixResult> ApplyAsync(CaseContext ctx, CancellationToken ct)
    {
        var f = ctx.Finding; var root = ctx.Workspace.Root;
        var path = Path.Combine(root, f.FilePath!);
        var lines = await File.ReadAllLinesAsync(path, ct);
        var site = FixEdits.FindMethod(lines, f.LineStart ?? 1);
        var testProj = Directory.GetFiles(Path.Combine(root, "tests"), "*.csproj", SearchOption.AllDirectories).First();
        var testDir = Path.GetDirectoryName(testProj)!;
        var existingTest = Directory.GetFiles(testDir, "*Tests.cs", SearchOption.AllDirectories).Select(File.ReadAllText).FirstOrDefault(t => t.Contains(site.ClassName)) ?? "";
        var helpers = FixEdits.PublicApi(Directory.GetFiles(Path.Combine(root, "src"), "*.cs", SearchOption.AllDirectories));
        var rp = cfg.RulePacks["unsafe_code"];
        var provider = FixEdits.ProviderFor(rp, site.Usings);
        var providerText = provider.Value?.Guidance ?? "Database library: see the file usings.";
        List<ComponentInput> Inputs(string? repairNote) =>
        [
            new("finding", $"finding:{f.FindingId}", LlmStep.FindingJson(f) + $"\nclass: {site.ClassName}  method: {site.Symbol}  namespace: {site.Namespace}"),
            new("code_snippet", f.CodeSnippetRef ?? $"file:{f.FilePath}#{site.Symbol}", site.MethodText(lines)),
            new("rule_pack", $"rule-packs/unsafe_code@{rp.Version}", rp.FixGuidance + "\n" + providerText + "\nFile usings:\n" + string.Join('\n', site.Usings)),
            new("tool_output", $"tests:{Path.GetRelativePath(root, testDir)}", "Existing test example:\n" + FixEdits.Truncate(existingTest, 1800) + "\n\nPublic API in src:\n" + string.Join('\n', helpers)
                + (repairNote != null ? "\n\nYOUR PREVIOUS OUTPUT WAS REJECTED BEFORE BUILD: " + repairNote : "")),
            new("run_summary", $"run:{ctx.PackRunId}", $"PR #{f.PrNumber}; attempt 1"),
        ];
        var sev = f.SeverityEffective ?? f.SeverityScanner;
        var call = await step.RunAsync(ctx, "fix", "unsafe_code", "fix", "fix-unsafe-code-output", sev, Inputs(null), ct);
        string? Forbidden(ModelStepResult x) => FixEdits.ForbiddenToken(provider.Value, LibraryEvalFixer.Str(x.Json, "method_code"), LibraryEvalFixer.Str(x.Json, "test_code"));
        if (Forbidden(call) is { } bad)
            call = await step.RunAsync(ctx, "fix.repair", "unsafe_code", "fix", "fix-unsafe-code-output", sev,
                Inputs($"it used '{bad}', which does not exist in {provider.Key}. {providerText}"), ct);
        var updated = FixEdits.ReplaceMethod(lines, site, LibraryEvalFixer.Str(call.Json, "method_code"));
        await File.WriteAllTextAsync(path, updated, ct);
        var testFile = FixEdits.TestFilePath(testDir, site);
        Directory.CreateDirectory(Path.GetDirectoryName(testFile)!);
        await File.WriteAllTextAsync(testFile, FixEdits.ComposeTestFile(existingTest, site, f.CweIds.FirstOrDefault(), LibraryEvalFixer.Str(call.Json, "test_code")), ct);
        return new FixResult(true, false, $"Rewrote {site.ClassName}.{site.Symbol}; added {Path.GetFileName(testFile)}", Notes: new()
        {
            ["symbol"] = $"{site.ClassName}.{site.Symbol}", ["test_file"] = Path.GetRelativePath(root, testFile), ["explanation"] = LibraryEvalFixer.Str(call.Json, "explanation"),
        });
    }
}

/// <summary>Mirrors BinaryLicenceFixer: remove a committed binary (+ ignore rule); for a licence clash propose options and hand the decision to a human.</summary>
public sealed class BinaryLicenceEvalFixer(ConfigSnapshot cfg, IModelStep step, IProcessRunner proc) : IEvalFixer
{
    public string Id => "binary_licence";

    public Task<FixResult> ApplyAsync(CaseContext ctx, CancellationToken ct) =>
        ctx.Finding.IssueType == IssueTypes.Licence ? LicenceAsync(ctx, ct) : BinaryAsync(ctx, ct);

    async Task<FixResult> BinaryAsync(CaseContext ctx, CancellationToken ct)
    {
        var rel = ctx.Finding.FilePath!; var root = ctx.Workspace.Root;
        var r = await proc.RunAsync("git", ["rm", "--quiet", rel], root, ct, 120);
        if (r.ExitCode != 0) throw new InvalidOperationException(r.StdErr.Trim());
        var pattern = FixEdits.BinaryIgnorePattern(rel);
        var gi = Path.Combine(root, ".gitignore");
        var existing = File.Exists(gi) ? await File.ReadAllTextAsync(gi, ct) : "";
        if (!existing.Contains(pattern)) await File.WriteAllTextAsync(gi, FixEdits.AppendIgnoreRule(existing, pattern), ct);
        return new FixResult(true, false, $"Removed {rel}; ignore rule {pattern}");
    }

    async Task<FixResult> LicenceAsync(CaseContext ctx, CancellationToken ct)
    {
        var f = ctx.Finding; var root = ctx.Workspace.Root;
        var rp = cfg.RulePacks["licence"];
        var verdict = FixEdits.LicenceVerdict(rp, f.LicenceId);
        var dir = f.ComponentName!.Replace("file:", "");
        var files = Directory.Exists(Path.Combine(root, dir)) ? Directory.GetFiles(Path.Combine(root, dir)).Select(Path.GetFileName).Order(StringComparer.Ordinal).ToList() : [];
        var code = files.Where(x => x!.EndsWith(".cs")).Select(x => File.ReadAllText(Path.Combine(root, dir, x!))).FirstOrDefault() ?? "";
        var call = await step.RunAsync(ctx, "fix", "binary_licence", "fix", "fix-licence-output", f.SeverityEffective ?? f.SeverityScanner,
        [
            new("finding", $"finding:{f.FindingId}", LlmStep.FindingJson(f) + $"\nother_locations: {string.Join(", ", f.OtherLocations)}\npolicy_verdict: {verdict}"),
            new("rule_pack", $"rule-packs/licence@{rp.Version}", rp.RawYaml),
            new("run_summary", $"run:{ctx.PackRunId}", $"Vendored component {dir}: files {string.Join(", ", files)}; code size {code.Split('\n').Length} lines"),
        ], ct);
        var alts = call.Json.GetProperty("alternatives").EnumerateArray().Select(x => x.GetString()!).ToList();
        lock (ctx) ctx.HumanTasks.Add("licence_decision");
        return new FixResult(false, true, $"{f.LicenceId} clash in {dir}: options proposed, decision routed to a human", "licence_decision",
            new() { ["alternatives"] = string.Join(" | ", alts), ["policy_verdict"] = verdict, ["reviewer_note"] = LibraryEvalFixer.Str(call.Json, "reviewer_note") });
    }
}
